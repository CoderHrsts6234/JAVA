package ElseIf;

public class ElseIf_If {
	public static void main(String[] args) {
		int num1 = 100;
		int num2 = 200;
		
		if(num1 == num2) {
			System.out.println("Yes, they are equal");
			}
		else if (num1 != num2) {
			System.out.println("No, they are not");
		}
		System.out.println("The program is done");
	}

}
